// Writes extension/content/prehide.css from the `hide` selectors in content/rules.js,
// so a known banner is invisible from the very first paint.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const ext = new URL('../extension/', import.meta.url);
const sandbox = {};
vm.runInNewContext(readFileSync(new URL('content/rules.js', ext), 'utf8'), sandbox);

const selectors = [...new Set(
  sandbox.CPR.rules
    .filter((r) => r.prehide !== false && r.conceal !== false)
    .flatMap((r) => r.hide || []),
)];

const css = `/* Generated by scripts/gen-prehide.mjs from content/rules.js. Edit the rules, not this file.
 * Known consent boxes stay laid out (their scripts keep working) but invisible until the
 * engine has answered them. data-cpr-off = paused on this site, data-cpr-done = finished. */
html:not([data-cpr-off]):not([data-cpr-done]) :is(
  ${selectors.join(',\n  ')}
) {
  opacity: 0 !important;
  pointer-events: none !important;
}
`;

writeFileSync(new URL('content/prehide.css', ext), css);
console.log(`prehide.css: ${selectors.length} selectors`);
